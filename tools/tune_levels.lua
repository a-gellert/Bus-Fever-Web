-- Offline level tuner: for every campaign level tries several seeds and keeps the one whose
-- casual-player fail rate is closest to the sawtooth target. Writes modules/meta/level_seeds.lua.
-- Run: node tools/tune_levels.js [levels]   (takes minutes; run after any curve/generator change)
local levels = require("modules.meta.levels")
local level_gen = require("modules.sim.level_gen")
local rules = require("modules.sim.rules")
local solver = require("modules.sim.solver")
local rng = require("modules.sim.rng")

local N = tonumber(os.getenv("LEVELS") or 100)
local CANDIDATES, RUNS = 8, 12

-- target casual fail rate by tooth position
local TARGET = { [0.2] = 0.15, [0.4] = 0.25, [0.6] = 0.35, [1.0] = 0.55, [0.0] = 0.05 }

for k in pairs(levels.SEEDS) do levels.SEEDS[k] = nil end -- tune from raw seeds
local lines = {}
for n = 1, N do
	local _, t = levels.difficulty(n)
	local target = TARGET[t] or 0.3
	if n <= 3 then target = 0 elseif n <= 6 then target = target * 0.5 end
	local best_k, best_err, best_rate
	for k = 0, CANDIDATES - 1 do
		local p = levels.params(n)
		p.seed = p.seed + k * 104729
		local lv = level_gen.generate(p)
		local st = rules.new(lv)
		local fails = 0
		for r = 1, RUNS do
			if not solver.play_casual(st, rng.new(n * 1000 + r), 40, 8) then fails = fails + 1 end
		end
		local rate = fails / RUNS
		local err = math.abs(rate - target)
		if not best_err or err < best_err then best_k, best_err, best_rate = k, err, rate end
		if err < 0.05 then break end
	end
	lines[#lines + 1] = string.format("\t[%d] = %d, -- fail %d%% (target %d%%)", n, best_k * 104729,
		math.floor(best_rate * 100 + 0.5), math.floor(target * 100 + 0.5))
	print(lines[#lines])
end


-- fengari has no io: print the file after a marker, the shell wrapper writes it
print("----FILE----")
print("-- Generated by tools/tune_levels.lua: seed offset per level (casual-player fail rate in comments).")
print("return {\n" .. table.concat(lines, "\n") .. "\n}")
