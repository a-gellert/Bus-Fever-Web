// Runs tools/tune_levels.lua under fengari and writes modules/meta/level_seeds.lua.
// Levels are split across worker processes (they are CPU-bound and independent).
// Usage: node tools/tune_levels.js [levels=100]
const { execFile } = require('child_process');
const { promisify } = require('util');
const fs = require('fs');
const path = require('path');

const execFileP = promisify(execFile);
const root = path.join(__dirname, '..');
const levels = Math.max(1, parseInt(process.argv[2] || '100', 10));
const jobs = Math.max(1, Math.min(levels, parseInt(process.env.TUNE_JOBS || '4', 10)));

function chunkSize() { return Math.ceil(levels / jobs); }

(async () => {
  const ranges = [];
  for (let start = 1; start <= levels; start += chunkSize()) {
    ranges.push({ start, end: Math.min(levels, start + chunkSize() - 1) });
  }
  console.log(`tuning ${levels} levels in ${ranges.length} jobs...`);
  const runs = ranges.map((r) => execFileP(process.execPath, [path.join(__dirname, 'run_tests.js'), 'tools/tune_levels.lua'], {
    cwd: root,
    env: { ...process.env, LEVELS: String(levels), START: String(r.start), END: String(r.end) },
    encoding: 'utf8',
    maxBuffer: 1 << 26,
  }));
  const outputs = await Promise.all(runs);
  const seedLines = [];
  for (const { stdout } of outputs) {
    const [log, file] = stdout.split('----FILE----\n');
    if (log) process.stdout.write(log);
    if (!file) throw new Error('tuner produced no file');
    const body = file.match(/return \{\n([\s\S]*?)\n\}/);
    if (!body) throw new Error('tuner produced no seed table');
    for (const line of body[1].split(/\r?\n/)) if (line.trim()) seedLines.push(line);
  }
  seedLines.sort((a, b) => {
    const na = Number((a.match(/\[(\d+)\]/) || [])[1] || 0);
    const nb = Number((b.match(/\[(\d+)\]/) || [])[1] || 0);
    return na - nb;
  });
  const out = '-- Generated by tools/tune_levels.lua: seed offset per level (casual-player fail rate in comments).\n' +
    'return {\n' + seedLines.join('\n') + '\n}\n';
  fs.writeFileSync(path.join(root, 'modules/meta/level_seeds.lua'), out);
  console.log(`wrote modules/meta/level_seeds.lua (${seedLines.length} levels)`);
})().catch((e) => {
  console.error(e.stderr || e.message || e);
  process.exit(1);
});
